import fs from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const outputFile = path.join(rootDir, 'src', 'data', 'generatedDocs.ts');

const mdFiles = fs
  .readdirSync(rootDir, { withFileTypes: true })
  .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith('.md'))
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b));

const entries = mdFiles.map((filename) => {
  const content = fs.readFileSync(path.join(rootDir, filename), 'utf8');
  return `  ${JSON.stringify(filename)}: ${JSON.stringify(content)},`;
});

const nextOutput = `// Auto-generated by scripts/syncDocsManifest.mjs — do not edit manually.\nexport const ROOT_MARKDOWN_FILES: Record<string, string> = {\n${entries.join('\n')}\n};\n`;

const existing = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, 'utf8') : '';
if (existing !== nextOutput) {
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(outputFile, nextOutput, 'utf8');
  console.log(`Synced ${mdFiles.length} markdown deliverables to src/data/generatedDocs.ts`);
} else {
  console.log(`Docs manifest already up to date (${mdFiles.length} files).`);
}
